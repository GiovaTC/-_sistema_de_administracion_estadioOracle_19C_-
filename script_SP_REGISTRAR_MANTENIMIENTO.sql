CREATE OR REPLACE PROCEDURE
PR_REGISTRAR_MANTENIMIENTO (
    P_ESTADIO_ID IN NUMBER,
    P_DESCRIPCION IN VARCHAR2,
    P_RESPONSABLE IN VARCHAR2
)
AS
BEGIN

    INSERT INTO MANTENIMIENTOS (
        ESTADIO_ID,
        DESCRIPCION,
        FECHA_PROGRAMADA,
        RESPONSABLE,
        ESTADO
    )
    VALUES (
        P_ESTADIO_ID,
        P_DESCRIPCION,
        SYSDATE,
        P_RESPONSABLE,
        'PENDIENTE'
    );

    COMMIT;

END;
/

BEGIN
    PR_REGISTRAR_MANTENIMIENTO(
        1,
        'Mantenimiento de césped',
        'Personal técnico'
    );
END;
/

COMMIT;