CREATE TABLE ESTADIOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(120) NOT NULL,
    CIUDAD VARCHAR2(100),
    DIRECCION VARCHAR2(200),
    CAPACIDAD NUMBER NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO',
    FECHA_REGISTRO DATE DEFAULT SYSDATE
);

CREATE TABLE CANCHAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ESTADIO_ID NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    TIPO_SUPERFICIE VARCHAR2(50),
    LARGO NUMBER(6,2),
    ANCHO NUMBER(6,2),
    ESTADO VARCHAR2(20) DEFAULT 'DISPONIBLE',

    CONSTRAINT FK_CANCHA_ESTADIO
    FOREIGN KEY (ESTADIO_ID)
    REFERENCES ESTADIOS(ID)
);

CREATE TABLE TRIBUNAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ESTADIO_ID NUMBER NOT NULL,
    NOMBRE VARCHAR2(100),
    CAPACIDAD NUMBER NOT NULL,

    CONSTRAINT FK_TRIBUNA_ESTADIO
    FOREIGN KEY (ESTADIO_ID)
    REFERENCES ESTADIOS(ID)
);

CREATE TABLE LOCALIDADES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TRIBUNA_ID NUMBER NOT NULL,
    SECTOR VARCHAR2(50),
    NUMERO_SILLA NUMBER,
    TIPO VARCHAR2(30),
    ESTADO VARCHAR2(20) DEFAULT 'DISPONIBLE',

    CONSTRAINT FK_LOCALIDAD_TRIBUNA
    FOREIGN KEY (TRIBUNA_ID)
    REFERENCES TRIBUNAS(ID)
);

CREATE TABLE EQUIPOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    CIUDAD VARCHAR2(100),
    ENTRENADOR VARCHAR2(100),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO'
);

CREATE TABLE PARTIDOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ESTADIO_ID NUMBER NOT NULL,
    EQUIPO_LOCAL_ID NUMBER NOT NULL,
    EQUIPO_VISITANTE_ID NUMBER NOT NULL,
    FECHA_PARTIDO TIMESTAMP NOT NULL,
    MARCADOR_LOCAL NUMBER DEFAULT 0,
    MARCADOR_VISITANTE NUMBER DEFAULT 0,
    ESTADO VARCHAR2(30) DEFAULT 'PROGRAMADO',

    CONSTRAINT FK_PARTIDO_ESTADIO
    FOREIGN KEY (ESTADIO_ID) REFERENCES ESTADIOS(ID),

    CONSTRAINT FK_PARTIDO_LOCAL
    FOREIGN KEY (EQUIPO_LOCAL_ID) REFERENCES EQUIPOS(ID),

    CONSTRAINT FK_PARTIDO_VISITANTE
    FOREIGN KEY (EQUIPO_VISITANTE_ID) REFERENCES EQUIPOS(ID)
);

CREATE TABLE CLIENTES_B (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(120) NOT NULL,
    DOCUMENTO VARCHAR2(30) UNIQUE,
    TELEFONO VARCHAR2(30),
    CORREO VARCHAR2(120),
    FECHA_REGISTRO DATE DEFAULT SYSDATE
);

CREATE TABLE RESERVAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENTE_ID NUMBER NOT NULL,
    CANCHA_ID NUMBER NOT NULL,
    FECHA_RESERVA DATE NOT NULL,
    HORA_INICIO VARCHAR2(5) NOT NULL,
    HORA_FIN VARCHAR2(5) NOT NULL,
    VALOR NUMBER(12,2) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE',

    CONSTRAINT FK_RESERVA_CLIENTE
    FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTES_B(ID),

    CONSTRAINT FK_RESERVA_CANCHA
    FOREIGN KEY (CANCHA_ID) REFERENCES CANCHAS(ID)
);

CREATE TABLE PAGOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RESERVA_ID NUMBER NOT NULL,
    VALOR NUMBER(12,2) NOT NULL,
    METODO_PAGO VARCHAR2(40),
    FECHA_PAGO DATE DEFAULT SYSDATE,
    ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE',

    CONSTRAINT FK_PAGO_RESERVA
    FOREIGN KEY (RESERVA_ID) REFERENCES RESERVAS(ID)
);

CREATE TABLE MANTENIMIENTOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ESTADIO_ID NUMBER NOT NULL,
    DESCRIPCION VARCHAR2(300),
    FECHA_PROGRAMADA DATE,
    RESPONSABLE VARCHAR2(120),
    ESTADO VARCHAR2(30) DEFAULT 'PENDIENTE',

    CONSTRAINT FK_MANT_ESTADIO
    FOREIGN KEY (ESTADIO_ID) REFERENCES ESTADIOS(ID)
);

CREATE TABLE INVENTARIO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ESTADIO_ID NUMBER NOT NULL,
    PRODUCTO VARCHAR2(120),
    CANTIDAD NUMBER NOT NULL,
    UBICACION VARCHAR2(100),
    ESTADO VARCHAR2(30) DEFAULT 'ACTIVO',

    CONSTRAINT FK_INV_ESTADIO
    FOREIGN KEY (ESTADIO_ID) REFERENCES ESTADIOS(ID)
);

CREATE TABLE USUARIOS_A (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(120) NOT NULL,
    CORREO VARCHAR2(120) UNIQUE NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROL VARCHAR2(30) DEFAULT 'OPERADOR',
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO'
);

CREATE TABLE AUDITORIA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO VARCHAR2(120),
    OPERACION VARCHAR2(100),
    DESCRIPCION VARCHAR2(500),
    FECHA_REGISTRO TIMESTAMP DEFAULT SYSTIMESTAMP
);

